// Vapor accepts ESM and UTF-8 TextDecoder. Bundle the pinned codecs and adapt
// only their CommonJS export and PNG Latin-1 text helper for that runtime.
import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const require = createRequire(import.meta.url);
const root = fileURLToPath(new URL("../", import.meta.url));
const folder = new URL("../uni_modules/qt-ui/services/vendor/", import.meta.url);
const checking = process.argv.includes("--check");
// License tarballs mix LF and CRLF, and Windows checkouts may convert text
// files. Pin artifact bytes to LF so the check is identical on every host.
const lf = (text) => text.replace(/\r\n/g, "\n");
const result = await build({
  absWorkingDir: root,
  stdin: {
    contents: 'export { default as decodeJpeg } from "jpeg-js/lib/decoder.js";\nexport { decode as decodePng, encode as encodePng, convertIndexedToRgb } from "fast-png";',
    resolveDir: root,
    sourcefile: "media-codecs-entry.js",
  },
  bundle: true, write: false, format: "esm", platform: "browser", target: "es2018",
  legalComments: "inline", charset: "utf8",
  banner: { js: "// Generated by tools/build-media-codecs.mjs. Do not edit.\n// jpeg-js 0.4.4, fast-png 8.0.0, iobuffer 6.0.1, fflate 0.8.3.\n// JPEG decoder: Copyright 2011 notmasteryet, Apache-2.0.\n// Upstream licenses and notices are included in this directory." },
  plugins: [{
    name: "vapor-media-codecs",
    setup(builder) {
      builder.onLoad({ filter: /jpeg-js[\\/]lib[\\/]decoder\.js$/ }, ({ path }) => {
        const source = readFileSync(path, "utf8");
        const wrapper = /if \(typeof module !== 'undefined'\) \{[\s\S]*?\n\}\n\nfunction decode/;
        assert.match(source, wrapper, "review the adapter when changing jpeg-js");
        return { contents: source.replace(wrapper, "export default function decode"), loader: "js" };
      });
      builder.onLoad({ filter: /fast-png[\\/]lib[\\/]helpers[\\/]text\.js$/ }, ({ path }) => {
        const source = readFileSync(path, "utf8");
        const original = "const latin1Decoder = new TextDecoder('latin1');";
        assert.ok(source.includes(original), "review the adapter when changing fast-png");
        // PNG tEXt uses ISO-8859-1 byte values. No platform text codec is needed.
        const replacement = "const latin1Decoder = { decode(bytes) { let text = ''; for (const byte of bytes) text += String.fromCharCode(byte); return text; } };";
        return { contents: source.replace(original, replacement), loader: "js" };
      });
    },
  }],
});
const artifacts = new Map([["media-codecs.js", lf(result.outputFiles[0].text)]]);
for (const [name, version, levels] of [["jpeg-js", "0.4.4", 1], ["fast-png", "8.0.0", 2], ["iobuffer", "6.0.1", 2], ["fflate", "0.8.3", 2]]) {
  let directory = require.resolve(name);
  for (let index = 0; index < levels; index++) directory = dirname(directory);
  assert.equal(JSON.parse(readFileSync(join(directory, "package.json"), "utf8")).version, version);
  artifacts.set(name + "-LICENSE.txt", lf(readFileSync(join(directory, "LICENSE"), "utf8")));
}
artifacts.set("Apache-2.0.txt", lf(readFileSync(require.resolve("typescript/LICENSE.txt"), "utf8")));
if (!checking) mkdirSync(folder, { recursive: true });
for (const [name, contents] of artifacts) {
  const path = new URL(name, folder);
  if (checking) assert.equal(lf(readFileSync(path, "utf8")), contents, name + " must match its pinned source; run npm run build:media-codecs");
  else writeFileSync(path, contents);
}
console.log(checking ? "Media codecs match their pinned sources and runtime adapters." : "Generated the licensed media codecs for Vapor.");
